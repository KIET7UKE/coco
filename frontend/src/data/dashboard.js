function seeded(seed) {
  let s = seed;
  return () => {
    s = (s * 16807) % 2147483647;
    return (s - 1) / 2147483646;
  };
}

function series(length, base, spread, seed, trend = 0) {
  const rand = seeded(seed);
  return Array.from({ length }, (_, i) =>
    Math.max(0, Math.round(base + trend * i + (rand() - 0.5) * spread)),
  );
}

