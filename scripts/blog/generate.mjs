import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { essays } from './essays.mjs'
import { posts, topics } from './posts.mjs'
import { article } from './seo-article.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const contentDir = path.join(root, 'frontend', 'src', 'content')
const site = 'https://coco.hibarri.com'

const topicBySlug = Object.fromEntries(topics.map((t) => [t.slug, t]))

export function slugify(value) {
  return value
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
}

function prepare(list) {
  const withSlugs = list.map((post) => ({ ...post, slug: slugify(post.title) }))
  const seen = new Set()
  for (const post of withSlugs) {
    const key = `${post.topic}/${post.slug}`
    if (seen.has(key)) throw new Error(`Duplicate path ${key}`)
    seen.add(key)
    if (!essays[post.essay]) throw new Error(`Missing essay ${post.essay} for ${key}`)
    if (post.also && !essays[post.also]) throw new Error(`Missing essay ${post.also}`)
    if (!topicBySlug[post.topic]) throw new Error(`Missing topic ${post.topic}`)
  }
  const built = withSlugs.map((post) => article(post, withSlugs))
  const openingByText = new Map()
  for (const post of built) {
    const opening = post.body.replace(/^---[\s\S]*?---\s*/, '').split(/\n\s*\n/)[0].trim()
    const previous = openingByText.get(opening)
    if (previous) throw new Error(`Duplicate opening in ${previous} and ${post.topic}/${post.slug}`)
    openingByText.set(opening, `${post.topic}/${post.slug}`)
  }
  return built
}

export function buildPosts() {
  return prepare(posts)
}

function writeFiles(built) {
  fs.rmSync(contentDir, { recursive: true, force: true })
  const catalog = []
  for (const post of built) {
    const dir = path.join(contentDir, post.topic)
    fs.mkdirSync(dir, { recursive: true })
    fs.writeFileSync(path.join(dir, `${post.slug}.md`), post.body)
    catalog.push({
      topic: post.topic,
      topicTitle: post.topicTitle,
      slug: post.slug,
      title: post.title,
      description: post.description,
    })
  }

  const catalogSource = `/* Generated by scripts/blog/generate.mjs. Edit posts there and regenerate. */\nexport const topics = ${JSON.stringify(topics, null, 2)}\n\nexport const posts = ${JSON.stringify(catalog, null, 2)}\n`
  fs.writeFileSync(path.join(contentDir, 'catalog.js'), catalogSource)

  const sitemapPath = path.join(root, 'frontend', 'public', 'sitemap.xml')
  const urls = [
    ['/', 'weekly', '1.0'],
    ['/investors', 'weekly', '0.9'],
    ['/live', 'daily', '0.9'],
    ['/packages', 'weekly', '0.8'],
    ['/blog', 'weekly', '0.8'],
    ...topics.map((topic) => [`/${topic.slug}`, 'weekly', '0.7']),
    ...built.map((post) => [`/${post.topic}/${post.slug}`, 'monthly', '0.6']),
  ]
  const body = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    ...urls.map(([loc, freq, priority]) => `  <url><loc>${site}${loc}</loc><lastmod>2026-10-12</lastmod><changefreq>${freq}</changefreq><priority>${priority}</priority></url>`),
    '</urlset>',
    '',
  ].join('\n')
  fs.writeFileSync(sitemapPath, body)
  return built.length
}

const built = buildPosts()
const count = writeFiles(built)
const words = built.reduce((sum, post) => sum + post.body.split(/\s+/).length, 0)
const lowest = built.reduce((min, post) => Math.min(min, post.density), 1)
const lowestCoco = built.reduce((min, post) => Math.min(min, post.cocoDensity), 1)
const under = built.filter((post) => post.density < 0.015 || post.cocoDensity < 0.015)
console.log(`Wrote ${count} posts, about ${Math.round(words / count)} words, lowest keyword density ${(lowest * 100).toFixed(2)}%, lowest Coco density ${(lowestCoco * 100).toFixed(2)}%`)
if (under.length) {
  console.log(under.map((post) => `${post.keyword} ${(post.density * 100).toFixed(2)}% / Coco ${(post.cocoDensity * 100).toFixed(2)}%`).join('\n'))
  process.exitCode = 1
}
